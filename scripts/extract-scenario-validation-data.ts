import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadScenarioMetadata } from "../lib/scenarios";

type ValidationItem = {
  scenario_id: string;
  scenario_text_en: string;
};

type AdminKeyRow = ValidationItem & {
  intended_mft_foundation: string;
  mft_category: string;
};

const outputDir = path.join(process.cwd(), "results", "processed", "scenario_validation_interface");

const foundationMap: Record<string, string> = {
  "Care/Harm": "Care/Harm",
  "Loyalty/Betrayal": "Loyalty/Betrayal",
  "Authority/Subversion": "Authority/Subversion",
  "Fairness/Cheating": "Fairness/Cheating",
  "Sanctity/Degradation": "Sanctity/Degradation",
  "Loyalty/Fairness": "Loyalty/Betrayal",
  "Authority/Loyalty": "Authority/Subversion",
  "Fairness/Care": "Fairness/Cheating",
  Sanctity: "Sanctity/Degradation"
};

async function main() {
  await mkdir(outputDir, { recursive: true });
  const scenarios = await loadScenarioMetadata();
  const rows: AdminKeyRow[] = scenarios
    .map((scenario) => ({
      scenario_id: scenario.scenario_id,
      intended_mft_foundation: normalizeFoundation(scenario.mft_foundation),
      mft_category: scenario.mft_category,
      scenario_text_en: scenario.text_en
    }))
    .sort((a, b) => a.scenario_id.localeCompare(b.scenario_id, undefined, { numeric: true }));

  const fullItems = rows.map(coderSafeItem);
  const authorityItems = rows.filter((row) => row.intended_mft_foundation === "Authority/Subversion").map(coderSafeItem);

  await writeFile(path.join(outputDir, "scenario_validation_items.full.json"), JSON.stringify(fullItems, null, 2), "utf8");
  await writeFile(path.join(outputDir, "scenario_validation_items.authority_only.json"), JSON.stringify(authorityItems, null, 2), "utf8");
  await writeFile(path.join(outputDir, "scenario_validation_admin_key.csv"), toCsv(rows), "utf8");
  await writeFile(path.join(outputDir, "README.md"), readme(rows.length, authorityItems.length), "utf8");

  console.log(`Wrote ${fullItems.length} full blinded scenario items.`);
  console.log(`Wrote ${authorityItems.length} authority-only scenario items.`);
  console.log(`Output folder: ${outputDir}`);
  console.log("");
  console.log("Run the interface with:");
  console.log("  corepack pnpm dev");
  console.log("Then open:");
  console.log("  http://localhost:3000/scenario-validation");
}

function normalizeFoundation(foundation: string) {
  const normalized = foundationMap[foundation];
  if (!normalized) throw new Error(`Unsupported MFT foundation label: ${foundation}`);
  return normalized;
}

function coderSafeItem(row: AdminKeyRow): ValidationItem {
  return {
    scenario_id: row.scenario_id,
    scenario_text_en: row.scenario_text_en
  };
}

function readme(fullCount: number, authorityCount: number) {
  return `# Scenario Validation Interface Data

Generated by \`corepack pnpm scenario-validation-extract\`.

## Coder Interface

Start the local app:

\`\`\`powershell
corepack pnpm dev
\`\`\`

Open:

- Full blinded validation: http://localhost:3000/scenario-validation
- Authority-only internal review: http://localhost:3000/scenario-validation?mode=authority

## Counts

- Full blinded validation scenarios: ${fullCount}
- Authority-only internal review scenarios: ${authorityCount}

## Files

- \`scenario_validation_items.full.json\`: coder-safe full set; no intended foundation labels.
- \`scenario_validation_items.authority_only.json\`: coder-safe Authority/Subversion subset; no intended foundation labels.
- \`scenario_validation_admin_key.csv\`: admin-only key; do not give this file to coders.

Coder exports intentionally omit intended foundation labels. After two coders export CSV files, merge those exports with \`scenario_validation_admin_key.csv\` for agreement and intended-foundation validation.
`;
}

function toCsv(rows: AdminKeyRow[]) {
  const headers: Array<keyof AdminKeyRow> = ["scenario_id", "intended_mft_foundation", "mft_category", "scenario_text_en"];
  return `${headers.join(",")}\n${rows.map((row) => headers.map((header) => csvCell(row[header])).join(",")).join("\n")}\n`;
}

function csvCell(value: string) {
  return /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
