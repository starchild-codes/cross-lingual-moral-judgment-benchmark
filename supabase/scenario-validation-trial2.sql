create table if not exists public.scenario_validation_scenarios (
  scenario_id text primary key,
  scenario_text_en text not null,
  intended_mft_foundation text not null check (
    intended_mft_foundation in (
      'Care/Harm',
      'Fairness/Cheating',
      'Loyalty/Betrayal',
      'Authority/Subversion',
      'Sanctity/Degradation'
    )
  )
);

create table if not exists public.scenario_validation_responses (
  id bigint generated by default as identity primary key,
  coder_id text not null check (coder_id in ('Coder_A', 'Coder_B', 'Coder_C')),
  scenario_id text not null references public.scenario_validation_scenarios(scenario_id) on delete restrict,
  shown_order integer not null check (shown_order between 1 and 50),
  scenario_text_en text not null,
  coder_scenario_label text not null check (
    coder_scenario_label in (
      'Care/Harm',
      'Fairness/Cheating',
      'Loyalty/Betrayal',
      'Authority/Subversion',
      'Sanctity/Degradation'
    )
  ),
  coder_notes text not null default '',
  saved_at timestamptz not null default now(),
  submitted_at timestamptz,
  is_submitted boolean not null default false,
  unique (coder_id, scenario_id)
);

create index if not exists scenario_validation_responses_coder_idx
  on public.scenario_validation_responses(coder_id, shown_order);

alter table public.scenario_validation_scenarios enable row level security;
alter table public.scenario_validation_responses enable row level security;

